/** "CHSC 113953.c" / "\"CHSC 114089 \"" -> { code: "CHSC 113953", description } */
export function calcode(raw: string | null | undefined): { code: string | null; description: string | null } {
  const s = (raw ?? "").replace(/"/g, "").trim();
  const m = s.match(/^CHSC\s+(\d{6}(?:\.\d+)?)/);
  if (!m) return { code: s || null, description: null };
  return { code: s, description: CALCODE[m[1]] ?? CALCODE[m[1].split(".")[0]] ?? null };
}
